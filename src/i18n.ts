function mergeCopy(base: Copy, pack?: Pack): Copy {
  if (!pack) return base;
  return {
    ...base,
    ...pack,
    categories: { ...base.categories, ...pack.categories },
    tiers: { ...base.tiers, ...pack.tiers },
    rules: pack.rules ?? base.rules,
  };
}

/** Full UI copy for a locale, falling back to English for missing keys. */
export function copyFor(locale: Locale): Copy {
  return mergeCopy(EN, PACKS[locale]);
}

